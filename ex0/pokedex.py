def by_number(number: int) -> Pokemon:
    if number not in POKEDEX:
        message = f"no pokemon with national number {number}"
        raise UnknownPokemon(message)
    return POKEDEX[number]


def starters(generation: int) -> tuple[Pokemon, ...]:
    found = []
    for entry in POKEDEX.values():
        if entry.starter and entry.generation == generation:
            found.append(entry)
    return tuple(found)


def lookup(family: str, generation: int) -> Pokemon:
    for entry in POKEDEX.values():
        if entry.family == family and entry.generation == generation:
            if entry.evolves_at and entry.evolves:
                if not any(other.evolves_into is entry
                           for other in POKEDEX.values()):
                    return entry
    message = f"no {family} starter for generation {generation}"
    raise UnknownGeneration(message)
